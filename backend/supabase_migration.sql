-- 2. Table: inspections (Inspection Metadata & Drone Image Runs)
CREATE TABLE IF NOT EXISTS public.inspections (
    id VARCHAR(36) PRIMARY KEY,
    tower_id VARCHAR(100) NOT NULL,
    location VARCHAR(200),
    created_at TIMESTAMPTZ NOT NULL DEFAULT timezone('utc'::text, now()),
    original_filename VARCHAR(255) NOT NULL,
    original_path VARCHAR(500) NOT NULL,
    annotated_path VARCHAR(500) NOT NULL,
    confidence_threshold DOUBLE PRECISION NOT NULL DEFAULT 0.25,
    mode VARCHAR(20) NOT NULL DEFAULT 'demo',
    is_demo BOOLEAN NOT NULL DEFAULT TRUE,
    model_name VARCHAR(100) NOT NULL DEFAULT 'unloaded',
    fault_count INTEGER NOT NULL DEFAULT 0,
    high_priority_count INTEGER NOT NULL DEFAULT 0,
    review_status VARCHAR(30) NOT NULL DEFAULT 'Pending Review',
    status VARCHAR(20) NOT NULL DEFAULT 'completed',
    image_width INTEGER NOT NULL DEFAULT 0,
    image_height INTEGER NOT NULL DEFAULT 0,
    
    CONSTRAINT chk_inspection_review_status 
        CHECK (review_status IN ('Pending Review', 'Verified', 'Rejected')),
    CONSTRAINT chk_inspection_mode 
        CHECK (mode IN ('trained', 'demo')),
    CONSTRAINT chk_inspection_status 
        CHECK (status IN ('completed', 'failed', 'processing')),
    CONSTRAINT chk_inspection_dims 
        CHECK (image_width >= 0 AND image_height >= 0)
);


-- 3. Table: detections (Model Prediction Results Linked to Inspections)
CREATE TABLE IF NOT EXISTS public.detections (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    inspection_id VARCHAR(36) NOT NULL REFERENCES public.inspections(id) ON DELETE CASCADE,
    class_id INTEGER NOT NULL,
    class_name VARCHAR(100) NOT NULL,
    fault_class_id INTEGER REFERENCES public.fault_classes(id) ON DELETE SET NULL,
    confidence DOUBLE PRECISION NOT NULL,
    x1 DOUBLE PRECISION NOT NULL,
    y1 DOUBLE PRECISION NOT NULL,
    x2 DOUBLE PRECISION NOT NULL,
    y2 DOUBLE PRECISION NOT NULL,
    priority VARCHAR(20) NOT NULL DEFAULT 'Low',
    
    CONSTRAINT chk_detection_confidence 
        CHECK (confidence >= 0.0 AND confidence <= 1.0),
    CONSTRAINT chk_detection_bbox_x 
        CHECK (x2 >= x1 AND x1 >= 0.0),
    CONSTRAINT chk_detection_bbox_y 
        CHECK (y2 >= y1 AND y1 >= 0.0),
    CONSTRAINT chk_detection_priority 
        CHECK (priority IN ('High', 'Medium', 'Low'))
);


